def main() -> None:
    db = get_db()
    now = datetime.now(timezone.utc)

    docs: list[dict] = []
    for c in COURSES:
        docs.append({**c, "computed_at": now})

    db["courses"].drop()
    res = db["courses"].insert_many(docs)
    log.info("✓ Inserted %d courses", len(res.inserted_ids))

    by_provider: dict[str, int] = {}
    for d in docs:
        by_provider[d["provider"]] = by_provider.get(d["provider"], 0) + 1
    for prov, n in sorted(by_provider.items(), key=lambda kv: -kv[1]):
        log.info("  %-20s %d", prov, n)


if __name__ == "__main__":
    main()
